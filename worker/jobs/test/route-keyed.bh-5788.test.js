import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gatedFamilies, parseFragments, renderRoutesModule } from '../src/lib/route-families.js';
import { matcherSignature } from '../src/lib/router.js';

// A ROUTE FAMILY CAN BE NAMED BY ITS TICKET KEY (BH-5788).
//
// test/route-table.d/<ticket-key>-<family>.txt sits next to the numbered
// <NNN>-<family>.txt fragments. The key is unique per ticket, so two builds
// that each add a family never pick the same "next free" number. Key-named
// fragments sort after every numbered one (letters sort after digits).
const JOBS = fileURLToPath(new URL('..', import.meta.url));
const REPO = join(JOBS, '..', '..');
const STRAY = (f) => `not a <NNN>-<family>.txt or <ticket-key>-<family>.txt fragment: ${f}`;

test('K1 parseFragments reads a key-named fragment and still refuses a stray name', () => {
  const got = parseFragments(['010-a.txt', 'bh-5788-zz-probe.txt', 'bh-6005-4-foo.txt', 'bh-5235.2-bar.txt']);
  const pick = (file) => {
    const f = got.find((x) => x.file === file);
    return f && { num: f.num, key: f.key, family: f.family };
  };
  assert.deepEqual(pick('010-a.txt'), { num: '010', key: null, family: 'a' });
  assert.deepEqual(pick('bh-5788-zz-probe.txt'), { num: null, key: 'bh-5788', family: 'zz-probe' });
  assert.deepEqual(pick('bh-6005-4-foo.txt'), { num: null, key: 'bh-6005-4', family: 'foo' });
  assert.deepEqual(pick('bh-5235.2-bar.txt'), { num: null, key: 'bh-5235.2', family: 'bar' });
  for (const bad of ['bh-5788.txt', 'bh-5788-a.txt.orig', 'oops.txt', '10-a.txt', '010-A.txt', 'BH-1-a.txt', 'bh-1-4x.txt']) {
    assert.throws(() => parseFragments(['020-b.txt', bad]), (e) => e.message === STRAY(bad), bad);
  }
  assert.throws(() => parseFragments(['010-a.txt', 'bh-1-a.txt']),
    (e) => e.message === 'family a has two fragments: 010-a.txt and bh-1-a.txt');
  // Two keyed fragments never share an order number: they have none.
  assert.deepEqual(gatedFamilies(['bh-1-a.txt', 'bh-1-b.txt']), ['a', 'b']);
});

test('K2 numbered fragments come first, then keyed ones by name; aliases are unique', () => {
  const names = ['bh-2-b.txt', '010-a.txt', 'bh-1-c.txt'];
  assert.deepEqual(gatedFamilies(names), ['a', 'c', 'b']);
  const out = renderRoutesModule(names);
  assert.deepEqual(out.split('\n').filter((l) => l.startsWith('import')), [
    'import { routes as f010 } from "./routes/a.js";',
    'import { routes as f_bh_1_c } from "./routes/c.js";',
    'import { routes as f_bh_2_b } from "./routes/b.js";',
  ]);
  assert.match(out, /export const ROUTES = \[\n {2}\.\.\.f010,\n {2}\.\.\.f_bh_1_c,\n {2}\.\.\.f_bh_2_b,\n\];\n$/);
  assert.match(renderRoutesModule(['bh-5235.2-x-y.txt']), /import \{ routes as f_bh_5235_2_x_y \} from "\.\/routes\/x-y\.js";/);
  // Numbered-only input renders the bytes it rendered before this ticket.
  assert.equal(renderRoutesModule(['020-b.txt', '010-a.txt']), [
    '// GENERATED by worker/jobs/scripts/routes-build.mjs from worker/jobs/test/route-table.d/ (BH-4607).',
    '// Git-ignored. wrangler.jsonc build.command renders it before every bundle; Node reads test/lib/routes.node.js instead.',
    'import { routes as f010 } from "./routes/a.js";',
    'import { routes as f020 } from "./routes/b.js";',
    '',
    'export const FAMILIES = ["a", "b"];',
    '',
    'export const ROUTES = [',
    '  ...f010,',
    '  ...f020,',
    '];',
    '',
  ].join('\n'));
});

function scratchWorker() {
  const root = mkdtempSync(join(tmpdir(), 'bh5788-'));
  const jobs = join(root, 'worker', 'jobs');
  for (const d of ['src', 'scripts', 'schema.d', 'package.json', join('test', 'lib'), join('test', 'route-table.d')]) {
    cpSync(join(JOBS, d), join(jobs, d), { recursive: true });
  }
  rmSync(join(jobs, 'src', 'routes.gen.js'), { force: true });
  mkdirSync(join(root, 'catalog'));
  for (const c of ['lanes.json', 'llm-sites.json', 'context-budgets.json']) {
    const from = join(REPO, 'catalog', c);
    assert.ok(existsSync(from), `catalog/${c} is missing: run bin/lanes-build.sh --write and bin/llm-sites-build.sh --compose`);
    cpSync(from, join(root, 'catalog', c));
  }
  for (const d of ['package.json', 'src', 'schema']) {
    cpSync(join(REPO, 'agent-core', d), join(root, 'agent-core', d), { recursive: true });
  }
  return { root, jobs };
}

const PROBE = 'import { json } from "../lib/http.js";\n'
  + 'export const routes = [["GET", "/api/zz-probe", () => json(200, { ok: true })]];\n';

test('K3 routes-build.mjs refuses a key-named fragment that names no module', () => {
  const w = scratchWorker();
  try {
    writeFileSync(join(w.jobs, 'test', 'route-table.d', 'bh-1-nope.txt'), 'GET /api/nope-fixture\n');
    const r = spawnSync(process.execPath, [join(w.jobs, 'scripts', 'routes-build.mjs')], { encoding: 'utf8' });
    assert.equal(r.status, 1);
    assert.deepEqual(r.stderr.trim().split('\n'), ['routes-build: fragment bh-1-nope.txt names no src/routes/nope.js']);
    assert.ok(!existsSync(join(w.jobs, 'src', 'routes.gen.js')), 'a refused render wrote routes.gen.js');
  } finally {
    rmSync(w.root, { recursive: true, force: true });
  }
});

test('K4 + K5 a key-named family renders, loads the same under node, and answers through fetch', async () => {
  const w = scratchWorker();
  try {
    writeFileSync(join(w.jobs, 'src', 'routes', 'zz-probe.js'), PROBE);
    writeFileSync(join(w.jobs, 'test', 'route-table.d', 'bh-5788-zz-probe.txt'), 'GET /api/zz-probe\n');

    const gen = join(w.jobs, 'src', 'routes.gen.js');
    execFileSync(process.execPath, [join(w.jobs, 'scripts', 'routes-build.mjs')]);
    const rendered = await import(pathToFileURL(gen).href);
    const loaded = await import(pathToFileURL(join(w.jobs, 'test', 'lib', 'routes.node.js')).href);
    const sigs = (rows) => rows.map(([m, matcher]) => `${m} ${matcherSignature(matcher)}`);
    assert.deepEqual(rendered.FAMILIES, loaded.FAMILIES);
    assert.deepEqual(sigs(rendered.ROUTES), sigs(loaded.ROUTES));
    // Key-named fragments sort after every numbered one and among themselves by
    // file name, so the probe is last only until a later key exists in the tree.
    const names = readdirSync(join(w.jobs, 'test', 'route-table.d'));
    assert.deepEqual(rendered.FAMILIES, gatedFamilies(names));
    const i = rendered.FAMILIES.indexOf('zz-probe');
    const numbered = parseFragments(names).filter((f) => f.num !== null && rendered.FAMILIES.includes(f.family)).length;
    assert.ok(i >= numbered, `zz-probe at ${i} sorts after the ${numbered} numbered families`);
    let at = 0;
    for (const f of rendered.FAMILIES.slice(0, i)) at += (await import(pathToFileURL(join(w.jobs, 'src', 'routes', `${f}.js`)).href)).routes.length;
    assert.equal(sigs(rendered.ROUTES)[at], 'GET /api/zz-probe');

    const mod = await import(pathToFileURL(join(w.jobs, 'src', 'index.js')).href);
    const res = await mod.default.fetch(
      new Request('https://x/api/zz-probe', { headers: { authorization: 'Bearer tok-fixture-5788' } }),
      { HARNESS_SECRET: 'tok-fixture-5788' });
    assert.equal(res.status, 200);
    assert.deepEqual(await res.json(), { ok: true });
    assert.ok(readFileSync(join(w.jobs, 'src', 'index.js')).equals(readFileSync(join(JOBS, 'src', 'index.js'))),
      'registering the family changed index.js');
  } finally {
    rmSync(w.root, { recursive: true, force: true });
  }
});

test('K6 there is ONE route mechanism: no src/routes.d and no bin/routes-build.sh', () => {
  assert.equal(existsSync(join(JOBS, 'src', 'routes.d')), false, 'worker/jobs/src/routes.d is a second route mechanism');
  assert.equal(existsSync(join(REPO, 'bin', 'routes-build.sh')), false, 'bin/routes-build.sh is a second route generator');
});
