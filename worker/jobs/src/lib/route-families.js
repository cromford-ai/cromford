// harness-jobs — which route families make up ROUTES, read from the fragments.
//
// A gated route family is src/routes/<family>.js plus one fragment
// test/route-table.d/<NNN>-<family>.txt. The three-digit number is the
// family's place in the first-match-wins table, so ROUTES is the families'
// `routes` lists concatenated in fragment-name order. Two readers use this:
// scripts/routes-build.mjs renders src/routes.gen.js for the wrangler bundle,
// and test/lib/routes.node.js imports the same families when node loads the
// worker. Pure on purpose: no node: import, so it can sit in src/.
//
// A new family can instead take test/route-table.d/<ticket-key>-<family>.txt
// (BH-5788): the key (`bh-5788`, a child `bh-6005-4` or `bh-5235.2`) is unique
// per ticket, so two builds that each add a family never pick the same "next
// free" number. Key-named fragments have no number. They sort after every
// numbered one (letters sort after digits) and among themselves by file name.
// The family of a key-named fragment starts with a letter, so the key ends
// where the digits end.

// The same regexp test/route-table.test.js reads fragments with. Groups: 1 the
// number and 2 its family, or 3 the ticket key and 4 its family.
export const FRAG_RE = /^(?:(\d{3})-([a-z0-9-]+)|([a-z]+-\d+(?:[.-]\d+)?)-([a-z][a-z0-9-]*))\.txt$/;

// The families index.js imports itself into OPEN_ROUTES. They are matched
// BEFORE the bearer check, so adding one is a reviewed edit to index.js, never
// a fragment: a fragment can never put a route in front of the bearer.
export const OPEN_FAMILIES = new Set(["webhooks", "ci-durations", "ci-test-tiers", "suite-results"]);

// The fragments as [{ num, key, family, file, id }], sorted by file name. num is
// the three digits or null, key the ticket key or null, and id the import alias
// renderRoutesModule uses. It throws on a name the route-table test would not
// read, rather than skip it: a skipped fragment is a family silently left out
// of the table.
export function parseFragments(names) {
  const files = [...names].sort();
  const byNum = new Map();
  const byFamily = new Map();
  const out = [];
  for (const file of files) {
    const m = FRAG_RE.exec(file);
    if (!m) throw new Error(`not a <NNN>-<family>.txt or <ticket-key>-<family>.txt fragment: ${file}`);
    const num = m[1] ?? null;
    const key = m[3] ?? null;
    const family = m[2] ?? m[4];
    if (num !== null && byNum.has(num)) throw new Error(`two fragments share order number ${num}: ${byNum.get(num)} and ${file}`);
    if (byFamily.has(family)) throw new Error(`family ${family} has two fragments: ${byFamily.get(family)} and ${file}`);
    if (num !== null) byNum.set(num, file);
    byFamily.set(family, file);
    const id = num !== null ? `f${num}` : `f_${key}_${family}`.replace(/[.-]/g, "_");
    out.push({ num, key, family, file, id });
  }
  return out;
}

// The gated families in fragment order: every fragment but OPEN_FAMILIES.
export function gatedFamilies(names) {
  return parseFragments(names).filter((f) => !OPEN_FAMILIES.has(f.family)).map((f) => f.family);
}

// The exact text of src/routes.gen.js for these fragment names.
export function renderRoutesModule(names) {
  const frags = parseFragments(names).filter((f) => !OPEN_FAMILIES.has(f.family));
  return [
    "// GENERATED by worker/jobs/scripts/routes-build.mjs from worker/jobs/test/route-table.d/ (BH-4607).",
    "// Git-ignored. wrangler.jsonc build.command renders it before every bundle; Node reads test/lib/routes.node.js instead.",
    ...frags.map((f) => `import { routes as ${f.id} } from "./routes/${f.family}.js";`),
    "",
    `export const FAMILIES = [${frags.map((f) => JSON.stringify(f.family)).join(", ")}];`,
    "",
    "export const ROUTES = [",
    ...frags.map((f) => `  ...${f.id},`),
    "];",
    "",
  ].join("\n");
}
