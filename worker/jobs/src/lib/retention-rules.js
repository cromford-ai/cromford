// harness-jobs — the retention rules in worker/jobs/src/routes/retention.d/,
// composed (BH-8398.0).
//
// RULES was one literal in routes/retention.js, and every build that added a
// rule appended to the same lines of the same file. Now a new rule is a
// fragment: retention.d/bh-<n>[.<m>]-<name>.js, a module whose default export
// is an array of rules. Fragments compose in fragmentNames order: the numeric
// ticket key, then the file name. Two readers use this: retention-rules.node.js
// imports the fragments when node loads the worker, and
// scripts/retention-build.mjs renders src/retention-rules.gen.js for the
// wrangler bundle. Pure on purpose: no node: import, so it can sit in src/.

// Groups: 1 the ticket number, 2 the name.
export const FRAG_RE = /^bh-(\d+)(?:\.\d+)?-([a-z0-9][a-z0-9-]*)\.js$/;

// The fragment file names, sorted. A .js-like name that is not a fragment
// throws rather than being skipped: a skipped fragment is a rule silently left
// out. Other names (README.md) are ignored.
export function fragmentNames(names) {
  const keep = [];
  for (const name of names) {
    if (!/\.[cm]?js$/i.test(name)) continue;
    const m = FRAG_RE.exec(name);
    if (!m) throw new Error(`not a bh-<n>-<name>.js fragment: ${name}`);
    keep.push({ name, n: Number(m[1]) });
  }
  keep.sort((a, b) => a.n - b.n || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  return keep.map((k) => k.name);
}

// The rules one fragment module exports.
export function fragmentRules(file, mod) {
  const rules = mod && mod.default;
  if (!Array.isArray(rules)) throw new Error(`retention.d/${file}: default export is not an array`);
  return rules;
}

// rules, unchanged, or a throw on the first bad entry.
export function checkRules(rules) {
  if (!Array.isArray(rules)) throw new Error("RULES is not an array");
  const seen = new Set();
  rules.forEach((r, i) => {
    const name = r && typeof r.rule === "string" && r.rule ? r.rule : `#${i}`;
    for (const f of ["rule", "table", "key", "ids", "del"]) {
      if (!r || typeof r[f] !== "string" || !r[f]) throw new Error(`rule ${name}: ${f} must be a non-empty string`);
    }
    if (!Number.isInteger(r.def)) throw new Error(`rule ${name}: def must be an integer`);
    if (seen.has(r.rule)) throw new Error(`duplicate rule: ${r.rule}`);
    seen.add(r.rule);
  });
  return rules;
}

// The exact text of src/retention-rules.gen.js for these fragment names.
export function renderRulesModule(names) {
  const files = fragmentNames(names);
  return [
    "// GENERATED by worker/jobs/scripts/retention-build.mjs from worker/jobs/src/routes/retention.d/ (BH-8398.0).",
    "// Git-ignored. wrangler.jsonc build.command renders it before every bundle; Node reads src/lib/retention-rules.node.js instead.",
    'import { checkRules, fragmentRules } from "./lib/retention-rules.js";',
    ...files.map((f, i) => `import * as f${i} from "./routes/retention.d/${f}";`),
    "",
    `export const FRAGMENTS = [${files.map((f) => JSON.stringify(f)).join(", ")}];`,
    "",
    "export const RULES = checkRules([",
    ...files.map((f, i) => `  ...fragmentRules(${JSON.stringify(f)}, f${i}),`),
    "]);",
    "",
  ].join("\n");
}
