# tests/fc-siblings-parallel.bh-5520-test.sh — BH-5520 Task 4. A decompose
# sibling that declares `imports_contract: false` (the JSON literal), names no
# earlier sibling in `after`, and shares no extracted path with the contract is
# filed with NO `Blocked-by:` line, so it builds on main in parallel with the
# contract instead of stacking on the contract's branch. Every other sibling
# keeps today's bytes.
#
# Driven through the PRODUCTION entry point, the real bin/run-decompose.sh in
# dry-run mode (the shape tests/decompose-contract-first-test.sh uses), with the
# real bin/planned-files.sh as the path extractor. The dry run numbers the
# children parent+n, so the contract is #101 and the siblings are #102 up.
#
#   P1  grant: no Blocked-by, a soft DEPENDS on the contract, the parallel
#       sentence, the log line; the REAL bin/unblocked-children.sh reads the
#       body and offers no STACKABLE line for it (control: the hard sibling
#       next to it IS stackable); dep_declared_hard reads no hard blocker.
#   P1b grant with zero other siblings (a 2-object spec).
#   P2  a sibling with no field: byte-identical to the pre-change bytes.
#   P3  false + `after: ["2: ..."]` -> hard on both, refusal logged.
#   P4  false + a contract path in the body -> hard, CONTESTED, refusal logged.
#   P4b false + the child's extraction failed (rc 2) -> hard, refusal logged.
#   P4c false + the contract names no extractable path -> hard, refusal logged.
#   P4d false + a shared bin/ path next to unshared tests/ paths -> hard,
#       refusal logged (planned-files.sh drops bin/; the token check sees it).
#   P4e control for P4d: a different bin/ file -> granted.
#   P5  the STRING "false" (and literal true) -> today's bytes, no refusal line.
#   P6  a spec with no field anywhere: every child byte-identical, no new log.
#   P7  the in-app board lane: false is logged and the sibling stays hard.
#
# The expected bytes in P2/P5/P6 were generated by running these same specs
# through bin/run-decompose.sh at main cc75af7c (before BH-5520), and pasted
# here verbatim.
#   HARNESS_TEST_SANDBOX=1 bash tests/fc-siblings-parallel.bh-5520-test.sh
