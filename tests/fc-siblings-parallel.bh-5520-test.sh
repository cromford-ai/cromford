# drive <spec-json> — the real script, dry run, spec handed in. Output in $T/b.
drive() {
  scratch_rm "$T/b"; mkdir -p "$T/b"
  printf '%s\n' "$1" > "$T/b/children.json"
  printf 'SIZE_DECLARED: files=18 lines=1900\nSIZE_OVER: lines=1900>300; files=18>12\nSIZE_VERDICT: over\n' > "$T/b/size-gate.txt"
  : > "$T/agent.log"
  env HARNESS="$T/h" FLEET_CONF="$T/h/fleet.conf" AGENT_LOG="$T/agent.log" \
      DECOMPOSE_DRY_RUN=1 "$DEC" scoutish 100 TK-100 "$T/b" 300 12 2>&1
}
cmpf() { # cmpf <got> <want-file> <what>
  if cmp -s "$1" "$2"; then ok
  else bad "$3 is not byte-identical to the pre-change bytes:
$(diff -u "$2" "$1" 2>&1 | head -30)"; fi
}
PL() { cat "$T/b/pipeline.log" 2>/dev/null; }

