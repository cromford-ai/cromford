# spec_a <sibling-2 field json, e.g. `"imports_contract":false,`>
spec_a() {
  printf '[%s,\n {"title":"b slice",%s"after":[],"body":"Own file only.\\n\\nFiles: src/lib/b.ts%s"},\n {"title":"c slice","after":[],"body":"Own file only.\\n\\nFiles: src/lib/c.ts%s"}]\n' \
    "$CONTRACT_OBJ" "$1" "$OBS" "$OBS"
}

# ===========================================================================
# P1 — acceptance 1: an independent sibling is filed with no blocker
# ===========================================================================
OUT=$(drive "$(spec_a '"imports_contract":false,')"); RC=$?
[ "$RC" -eq 0 ] && ok || bad "P1 the dry-run drive must exit 0 (rc=$RC): $OUT"
K2="$T/b/children/child-2.md"; K3="$T/b/children/child-3.md"
[ -s "$K2" ] && ok || bad "P1 child-2.md was not written: $OUT"
grep -q '^Blocked-by:' "$K2" && bad "P1 the independent sibling must carry NO Blocked-by line: $(cat "$K2")" || ok
[ "$(grep '^DEPENDS:' "$K2" | head -1)" = "$SOFT_DEP" ] && ok || bad "P1 the first DEPENDS line is the soft contract line: $(grep '^DEPENDS:' "$K2")"
[ "$(grep -c '^DEPENDS:' "$K2")" -eq 1 ] && ok || bad "P1 one DEPENDS line (no earlier sibling): $(grep '^DEPENDS:' "$K2")"
