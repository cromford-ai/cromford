#!/bin/bash
# tests/module-map.bh-5240-test.sh — bin/lib/module-map.sh (mm_order, mm_load)
# and bin/module-map-build.sh (--write, --check), the module loader pattern.
#
#   MM-1 three fixture modules with after: deps load in dependency order, from
#        a written MODULES and from the headers alone; the C-sort tie-break;
#        an empty after: is a root; comma deps
#   MM-2 a cycle (two names, three names, self) and an unknown dep give rc 1
#        with the names, and nothing is sourced
#   MM-3 the static scans: a function in two modules, a heredoc that hides a
#        definition, a top-level declare with no -g
#   MM-4 a stale MODULES fails --check; a failed --write leaves it untouched;
#        an unchanged --write does not rewrite; mm_load on a bad MODULES
#   MM-5 a fourth module is one new file plus --write: nothing else changes
#   MM-6 the header matcher's negatives
#   MM-7 the real repo: --check rc 0 on bin/lib/mc, order unchanged from the shim
#   MM-8 usage errors give rc 2
# Run from anywhere (exit 0 = all pass).
set -uo pipefail
. "$(dirname "$0")/lib/scratch.sh" || exit 1
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL: $1"; }

DIR="$(cd "$(dirname "$0")/.." && pwd)"
LIB="$DIR/bin/lib/module-map.sh"
BUILD="$DIR/bin/module-map-build.sh"
[ -r "$LIB" ] || { echo "FAIL: $LIB missing"; exit 1; }
[ -x "$BUILD" ] || { echo "FAIL: $BUILD missing or not executable"; exit 1; }

# fx <name> — a fresh fixture repo root; sets FX (root) and M (its module dir).
fx() { FX="$T/$1"; M="$FX/bin/lib/fx"; scratch_rm "$FX" || exit 1; mkdir -p "$M"; }
# mod <name> <header line or ""> [extra body] — a fixture module that appends
# its name to _order when sourced and defines fn_<name>.
mod() {
  { echo '#!/bin/bash'; echo '# shellcheck shell=bash'
    [ -n "$2" ] && echo "$2"
    echo "_order=\"\${_order:-}$1 \""
    echo "fn_$1() { :; }"
    [ -n "${3:-}" ] && printf '%s\n' "$3"
  } > "$M/$1.sh"
}
# ld <dir> — mm_load <dir> in a fresh bash; LRC = rc, LORD = _order or UNSET.
ld() {
  local out
  out=$(timeout 20 bash -c '. "$1" || exit 9; mm_load "$2"; rc=$?; printf "%s|%s" "$rc" "${_order-UNSET}"' _ "$LIB" "$1" 2>"$T/lerr")
  LRC=${out%%|*}; LORD=${out#*|}
}
# ord <dir> — mm_order <dir>; ORC = rc, OOUT = the names on one line.
ord() { OOUT=$(timeout 20 bash -c '. "$1" || exit 9; mm_order "$2"' _ "$LIB" "$1" 2>"$T/oerr" | tr '\n' ' '); ORC=${PIPESTATUS[0]}; }
# bm <args> — the real build script on the current fixture root.
bm() { timeout 60 "$BUILD" --root "$FX" "$@" >"$T/out" 2>"$T/err"; RC=$?; }
sum() { sha256sum "$1" | cut -d' ' -f1; }

# ---- MM-1 dependency order --------------------------------------------------
fx r1
mod c '# module: c after: b'
mod b '# module: b after: a'
mod a '# module: a'
ld "$M"
[ "$LRC" = 0 ] && [ "$LORD" = "a b c " ] && ok || bad "MM-1 header fallback (no MODULES) must load a b c, got rc=$LRC order='$LORD' $(cat "$T/lerr")"
bm --write bin/lib/fx
[ "$RC" = 0 ] && [ -f "$M/MODULES" ] && ok || bad "MM-1 --write must create MODULES, rc=$RC $(cat "$T/err")"
[ "$(grep -v '^#' "$M/MODULES" | tr '\n' ' ')" = "a b c " ] && ok || bad "MM-1 MODULES must list a b c: $(cat "$M/MODULES")"
grep -q '^# bin/lib/fx/MODULES — generated by bin/module-map-build.sh' "$M/MODULES" && ok || bad "MM-1 MODULES must carry the generated banner"
ld "$M"
[ "$LRC" = 0 ] && [ "$LORD" = "a b c " ] && ok || bad "MM-1 mm_load from MODULES must load a b c, got rc=$LRC order='$LORD'"
bm bin/lib/fx
[ "$RC" = 0 ] && [ "$(tr '\n' ' ' < "$T/out")" = "a b c " ] && ok || bad "MM-1 print mode must print the order, got rc=$RC '$(cat "$T/out")'"
# The functions and globals a module defines outlive mm_load.
out=$(bash -c '. "$1"; mm_load "$2" && declare -F fn_a fn_b fn_c | tr "\n" " "' _ "$LIB" "$M")
[ "$out" = "fn_a fn_b fn_c " ] && ok || bad "MM-1 the modules' functions must be defined after mm_load, got '$out'"

fx tie
mod log '# module: log'
mod b '# module: b after: log'
mod a '# module: a after: log'
ord "$M"
[ "$ORC" = 0 ] && [ "$OOUT" = "log a b " ] && ok || bad "MM-1 tie: two ready modules go in C order (log a b), got rc=$ORC '$OOUT'"
fx root
mod z '# module: z after:'
mod y '# module: y after: z'
mod d '# module: d after: y,z'
ord "$M"
[ "$ORC" = 0 ] && [ "$OOUT" = "z y d " ] && ok || bad "MM-1 an empty after: is a root and comma deps count, want 'z y d', got rc=$ORC '$OOUT' $(cat "$T/oerr")"

# ---- MM-2 refusals ----------------------------------------------------------
fx cyc
mod a '# module: a after: b'
mod b '# module: b after: a'
mod m '# module: m'
ld "$M"
[ "$LRC" = 1 ] && ok || bad "MM-2 a cycle must give mm_load rc 1, got $LRC"
[ "$LORD" = UNSET ] && ok || bad "MM-2 a cycle must source nothing, not even the free module m: _order='$LORD'"
grep -q 'cycle: a -> b -> a' "$T/lerr" && ok || bad "MM-2 the cycle must be named: $(cat "$T/lerr")"
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q 'cycle: a -> b -> a' "$T/err" && ok || bad "MM-2 --check must refuse the cycle, rc=$RC $(cat "$T/err")"
fx cyc3
mod a '# module: a after: c'
mod b '# module: b after: a'
mod c '# module: c after: b'
ord "$M"
[ "$ORC" = 1 ] && grep -q 'cycle: a -> c -> b -> a' "$T/oerr" && ok || bad "MM-2 a three-name cycle must name all three, rc=$ORC $(cat "$T/oerr")"
fx self
mod a '# module: a after: a'
ord "$M"
[ "$ORC" = 1 ] && grep -q 'cycle: a -> a' "$T/oerr" && ok || bad "MM-2 a self-cycle must give rc 1, rc=$ORC $(cat "$T/oerr")"
fx unk
mod a '# module: a after: zz'
ld "$M"
[ "$LRC" = 1 ] && [ "$LORD" = UNSET ] && grep -q 'a after: zz, and no module is named zz' "$T/lerr" && ok || bad "MM-2 an unknown dep must give rc 1 and name it, rc=$LRC $(cat "$T/lerr")"
fx base
mod q '# module: r'
ord "$M"
[ "$ORC" = 1 ] && grep -q 'header names module r, and the name must be the basename q' "$T/oerr" && ok || bad "MM-2 a header name that is not the basename must fail, rc=$ORC $(cat "$T/oerr")"
fx zero
mod p ''
ord "$M"
[ "$ORC" = 1 ] && grep -q 'zero modules' "$T/oerr" && ok || bad "MM-2 a dir with no headed module must fail, rc=$ORC $(cat "$T/oerr")"

# ---- MM-3 the static scans --------------------------------------------------
fx dup
mod a '# module: a' 'f() { :; }'
mod b '# module: b after: a' 'function f() { :; }'
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q 'module-map: bin/lib/fx: f is defined in bin/lib/fx/a.sh and bin/lib/fx/b.sh' "$T/err" && ok || bad "MM-3 f() and function f() must be a duplicate, rc=$RC $(cat "$T/err")"
bm --write bin/lib/fx
[ "$RC" = 1 ] && [ ! -e "$M/MODULES" ] && ok || bad "MM-3 --write must write nothing on a duplicate, rc=$RC"
mod b '# module: b after: a' '  function   f ()   { :; }'
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q 'f is defined in' "$T/err" && ok || bad "MM-3 an indented 'function f ()' must be a duplicate, rc=$RC $(cat "$T/err")"
# HD is "<<", so this suite's own text holds no heredoc opener a static
# scanner (test-sources-lint, test-impact) would read as real.
HD='<''<'
mod b '# module: b after: a' "$(printf 'x=$(cat %s<"hi")\nf() { :; }' "$HD")"
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q 'f is defined in' "$T/err" && ok || bad "MM-3 a here-string must not open a heredoc that hides f(), rc=$RC $(cat "$T/err")"
# Controls: a definition inside a heredoc, or only in a comment, is not one.
fx doc
mod a '# module: a' 'f() { :; }'
mod b '# module: b after: a' "$(printf "cat %s'EOF'\nf() { :; }\nEOF\nusage() {\n\tcat %s-EOT\n\tf() { :; }\n\tEOT\n}\n# f() is a's" "$HD" "$HD")"
bm --write bin/lib/fx
[ "$RC" = 0 ] && ok || bad "MM-3 f() inside a heredoc or a comment is not a duplicate, rc=$RC $(cat "$T/err")"
mod b '# module: b after: a' "$(printf "cat %sEOF\nf() { :; }\n" "$HD")"
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q "heredoc ${HD}EOF never closes" "$T/err" && ok || bad "MM-3 an unclosed heredoc must be a finding, rc=$RC $(cat "$T/err")"
# The same name in two headerless files is never checked.
fx nohdr
mod a '# module: a'
mod p '' 'g() { :; }'
mod q '' 'g() { :; }'
bm --write bin/lib/fx
[ "$RC" = 0 ] && [ "$(grep -v '^#' "$M/MODULES")" = a ] && ok || bad "MM-3 headerless files are not modules and are not scanned, rc=$RC $(cat "$T/err")"
# Top-level declare.
for case_ in 'declare X=1|1' 'typeset X=1|1' 'declare -A MAP=()|1' 'local y=1|1' 'declare -g X=1|0' 'declare -gA MAP=()|0' 'declare -r -g X=1|0' '  local y=1|0'; do
  line=${case_%|*}; want=${case_##*|}
  fx decl
  mod a '# module: a' "$line"
  bm --check bin/lib/fx
  if [ "$want" = 1 ]; then
    [ "$RC" = 1 ] && grep -q "top-level \"$line\" with no -g" "$T/err" && ok || bad "MM-3 top-level '$line' must be refused, rc=$RC $(cat "$T/err")"
  else
    grep -q 'top-level' "$T/err" && bad "MM-3 '$line' must not be refused: $(cat "$T/err")" || ok
  fi
done
# Why the rule exists, at runtime: mm_load sources at function scope.
fx scope
mod a '# module: a' "$(printf 'declare -g KEEP=1\ndeclare LOST=1\nPLAIN=1')"
out=$(bash -c '. "$1"; mm_load "$2"; echo "${KEEP-unset} ${LOST-unset} ${PLAIN-unset}"' _ "$LIB" "$M")
[ "$out" = "1 unset 1" ] && ok || bad "MM-3 declare -g and plain assignments survive mm_load and a bare declare does not, got '$out'"

# ---- MM-4 stale MODULES and failed writes -----------------------------------
fx r4
mod a '# module: a'
mod b '# module: b after: a'
mod c '# module: c after: b'
bm --write bin/lib/fx
GOOD=$(cat "$M/MODULES")
bm --check bin/lib/fx
[ "$RC" = 0 ] && grep -q '^module-map: 1 dir(s) ok' "$T/out" && ok || bad "MM-4 a fresh MODULES must pass --check, rc=$RC $(cat "$T/err")"
printf '%s\n' "$GOOD" | sed 's/^b$/TMPX/; s/^c$/b/; s/^TMPX$/c/' > "$M/MODULES"
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q 'bin/lib/fx/MODULES: stale — run bin/module-map-build.sh --write' "$T/err" && ok || bad "MM-4 swapped lines must be stale, rc=$RC $(cat "$T/err")"
grep -q 'dir(s) ok' "$T/out" && bad "MM-4 a stale check must not print the ok line" || ok
# MODULES wins over the headers when present: the hand order is what loads.
ld "$M"
[ "$LRC" = 0 ] && [ "$LORD" = "a c b " ] && ok || bad "MM-4 mm_load must read the order from MODULES, got rc=$LRC '$LORD'"
printf '%s\n' "$GOOD" | grep -v '^c$' > "$M/MODULES"
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q stale "$T/err" && ok || bad "MM-4 a deleted line must be stale, rc=$RC"
rm -f "$M/MODULES"
bm --check bin/lib/fx
[ "$RC" = 1 ] && grep -q stale "$T/err" && ok || bad "MM-4 a missing MODULES next to headed modules must be stale, rc=$RC"
printf '%s\n' "$GOOD" > "$M/MODULES"
touch -d @1000000000 "$M/MODULES"
bm --write bin/lib/fx
[ "$RC" = 0 ] && [ "$(stat -c %Y "$M/MODULES")" = 1000000000 ] && [ ! -s "$T/out" ] && ok || bad "MM-4 an unchanged --write must not rewrite MODULES, rc=$RC mtime=$(stat -c %Y "$M/MODULES")"
mod d '# module: d after: e'
mod e '# module: e after: d'
B4=$(sum "$M/MODULES")
bm --write bin/lib/fx
[ "$RC" = 1 ] && [ "$(sum "$M/MODULES")" = "$B4" ] && ok || bad "MM-4 a --write on an invalid set must leave MODULES byte-identical, rc=$RC"
rm -f "$M/d.sh" "$M/e.sh"
# A MODULES name with no file: rc 1, the file named, nothing sourced.
printf '%s\nghost\n' "$GOOD" > "$M/MODULES"
ld "$M"
[ "$LRC" = 1 ] && [ "$LORD" = UNSET ] && grep -q "module ghost has no readable file $M/ghost.sh; nothing sourced" "$T/lerr" && ok || bad "MM-4 a listed module with no file must source nothing, rc=$LRC order='$LORD' $(cat "$T/lerr")"
printf '../x\n' > "$M/MODULES"
ld "$M"
[ "$LRC" = 1 ] && [ "$LORD" = UNSET ] && grep -q 'is not a module name' "$T/lerr" && ok || bad "MM-4 a MODULES line that is not a name must fail, rc=$LRC $(cat "$T/lerr")"
printf '# only a comment\n' > "$M/MODULES"
ld "$M"
[ "$LRC" = 1 ] && [ "$LORD" = UNSET ] && ok || bad "MM-4 an empty MODULES must fail, rc=$LRC"
# A module whose source fails: rc 1, named, the ones before it stay sourced.
printf '%s\n' "$GOOD" > "$M/MODULES"
mod b '# module: b after: a' 'return 1'
ld "$M"
[ "$LRC" = 1 ] && [ "$LORD" = "a b " ] && grep -q 'sourcing module b' "$T/lerr" && ok || bad "MM-4 a failed source must give rc 1 and name b, rc=$LRC order='$LORD' $(cat "$T/lerr")"

# ---- MM-5 a fourth module touches nothing else ------------------------------
fx r5
mod a '# module: a'
mod b '# module: b after: a'
mod c '# module: c after: b'
echo 'not a module' > "$FX/README"
bm --write bin/lib/fx
treesum() { (cd "$FX" && find . -type f ! -name d.sh ! -name MODULES | sort | xargs sha256sum); }
T0=$(treesum); M0=$(sum "$M/MODULES")
mod d '# module: d after: b'
bm --write bin/lib/fx
[ "$RC" = 0 ] && ok || bad "MM-5 --write with a fourth module must pass, rc=$RC $(cat "$T/err")"
[ "$(treesum)" = "$T0" ] && ok || bad "MM-5 adding d.sh must change no other file but MODULES"
[ "$(sum "$M/MODULES")" != "$M0" ] && ok || bad "MM-5 MODULES must change"
bm --check bin/lib/fx
[ "$RC" = 0 ] && ok || bad "MM-5 --check must pass after --write, rc=$RC $(cat "$T/err")"
ld "$M"
[ "$LRC" = 0 ] && [ "$LORD" = "a b c d " ] && ok || bad "MM-5 mm_load must give a b c d (c before d by name), got rc=$LRC '$LORD'"

# ---- MM-6 the header matcher's negatives ------------------------------------
# Not "# module:" lines at all: never a module, never an error.
for h in '# bin/lib/mc/log.sh — BH-477: the base module: MC_* globals, mc_log.' '#module: x' '# modules: x' '#  module: x'; do
  fx neg
  mod a '# module: a'
  mod x "$h"
  ord "$M"
  [ "$ORC" = 0 ] && [ "$OOUT" = "a " ] && ok || bad "MM-6 '$h' must not make a module, got rc=$ORC '$OOUT' $(cat "$T/oerr")"
done
# "# module:" lines off the grammar: never a module, and a loud error.
for h in '# module: X' '# module: x after: y # comment' '# module: x ' '# module:x' '# module: x after:y' '# module: x after: Y'; do
  fx mal
  mod a '# module: a'
  mod x "$h"
  ord "$M"
  [ "$ORC" = 1 ] && grep -qF "x.sh:3: malformed header \"$h\"" "$T/oerr" && ok || bad "MM-6 '$h' must be a malformed header naming its line, rc=$ORC $(cat "$T/oerr")"
done
# Only the first 30 lines count; CRLF is stripped.
fx l31
mod a '# module: a'
{ echo '#!/bin/bash'; for _ in $(seq 2 30); do echo '#'; done; echo '# module: x'; } > "$M/x.sh"
ord "$M"
[ "$ORC" = 0 ] && [ "$OOUT" = "a " ] && ok || bad "MM-6 a header on line 31 must not count, got rc=$ORC '$OOUT'"
{ echo '#!/bin/bash'; for _ in $(seq 2 29); do echo '#'; done; echo '# module: x after: a'; } > "$M/x.sh"
ord "$M"
[ "$ORC" = 0 ] && [ "$OOUT" = "a x " ] && ok || bad "MM-6 a header on line 30 counts, got rc=$ORC '$OOUT'"
printf '#!/bin/bash\r\n# module: x after: a\r\n' > "$M/x.sh"
ord "$M"
[ "$ORC" = 0 ] && [ "$OOUT" = "a x " ] && ok || bad "MM-6 a CRLF header counts, got rc=$ORC '$OOUT' $(cat "$T/oerr")"

# ---- MM-7 the real repo -----------------------------------------------------
"$BUILD" --check >"$T/out" 2>"$T/err"; RC=$?
# BH-5241: bin/lib/br has headers and a MODULES too, so the ok list names more
# than one dir; this pins that bin/lib/mc is one of them.
[ "$RC" = 0 ] && grep -qE '^module-map: [0-9]+ dir\(s\) ok \(([^)]* )?bin/lib/mc( [^)]*)?\)$' "$T/out" && ok || bad "MM-7 --check on the repo must pass and name bin/lib/mc, rc=$RC out=$(cat "$T/out") err=$(cat "$T/err")"
[ "$(grep -v '^#' "$DIR/bin/lib/mc/MODULES" | tr '\n' ' ')" = "log locks classify queue rebase settle " ] && ok || bad "MM-7 bin/lib/mc/MODULES must keep the shim's order: $(cat "$DIR/bin/lib/mc/MODULES")"
"$BUILD" bin/lib/mc >"$T/out" 2>"$T/err"; RC=$?
[ "$RC" = 0 ] && [ "$(tr '\n' ' ' < "$T/out")" = "log locks classify queue rebase settle " ] && ok || bad "MM-7 the headers alone must give the shim's order, rc=$RC '$(cat "$T/out")'"

# ---- MM-8 usage errors ------------------------------------------------------
timeout 20 bash -c '. "$1"; mm_load /nonexistent-bh-5240' _ "$LIB" 2>/dev/null; RC=$?
[ "$RC" = 2 ] && ok || bad "MM-8 mm_load on a missing dir must give rc 2, got $RC"
timeout 20 bash -c '. "$1"; mm_load ""' _ "$LIB" 2>/dev/null; RC=$?
[ "$RC" = 2 ] && ok || bad "MM-8 mm_load with no dir must give rc 2, got $RC"
fx r8
mod a '# module: a'
bm --bogus; [ "$RC" = 2 ] && ok || bad "MM-8 --bogus must give rc 2, got $RC"
bm bin/lib/nope; [ "$RC" = 2 ] && ok || bad "MM-8 a dir that does not exist must give rc 2, got $RC"
"$BUILD" --root "$T/no-such-root" --check >/dev/null 2>&1; RC=$?
[ "$RC" = 2 ] && ok || bad "MM-8 a missing --root must give rc 2, got $RC"
mkdir -p "$M/../fy"; cp "$M/a.sh" "$M/../fy/a.sh"
bm; [ "$RC" = 2 ] && ok || bad "MM-8 print mode over two dirs must give rc 2, got $RC"

echo "module-map.bh-5240: $PASS passed, $FAIL failed"
[ "$FAIL" = 0 ]
